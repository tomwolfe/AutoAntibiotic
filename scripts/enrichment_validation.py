def load_benchmark(data_dir: str):
    """Load known actives and decoys from CSVs. Returns (records, labels).

    Labels are 1 for known actives, 0 for decoys -- determined SOLELY
    from experimental measurement / independent property matching, never
    from a docking energy threshold.

    Actives come from data/active_site_actives.csv (21 known experimental
    PBP2a binders with pIC50 values). Decoys are sourced from 
    data/chembl_decoy_pool.csv and are property-matched to the actives
    using DUD-E methodology: MW ±10%, logP ±0.5, HBD/HBA ±1, rotatable bonds ±2,
    Tanimoto < 0.35 to any active. This replaces the previous BRICS recombination
    of actives, which created a circular validation.
    """
    records = []
    labels = []

    # Known actives (experimental PBP2a binders with measured pIC50)
    actives_path = os.path.join(data_dir, "active_site_actives.csv")
    if not os.path.exists(actives_path):
        log.error(f"  Known-actives file not found: {actives_path}")
        sys.exit(1)
    with open(actives_path, newline="") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            smi = row["smiles"].strip()
            cid = row["compound_id"].strip()
            if smi:
                records.append(P.CompoundRecord(compound_id=cid, smiles=smi))
                labels.append(1)  # active = known experimental binder
    log.info(f"  Loaded {sum(labels)} known actives")

    # Load property-matched decoys from the chembl_decoy_pool.csv
    # This pool contains property-matched decoys independent of the actives
    decoys_path = os.path.join(data_dir, "chembl_decoy_pool.csv")
    if not os.path.exists(decoys_path):
        log.error(f"  ChEMBL decoy pool file not found: {decoys_path}")
        sys.exit(1)
    
    # For enrichment validation, we need a balanced set of decoys
    # We'll take a subset from the pool that's roughly the same size as known_decoys.csv
    # (150 decoys) to maintain compatibility with existing downstream code
    with open(decoys_path, newline="") as fh:
        reader = csv.DictReader(fh)
        decoy_candidates = []
        for row in reader:
            smi = row["smiles"].strip()
            cid = row["compound_id"].strip()
            if smi:
                decoy_candidates.append((cid, smi))
    
    log.info(f"  Loaded {len(decoy_candidates)} candidates from ChEMBL decoy pool")
    
    # Use property-matched filtering (same as DUD-E methodology)
    from rdkit import Chem
    # Create property templates from actives for matching
    from rdkit.Chem import Descriptors, AllChem, rdMolDescriptors
    from rdkit import DataStructs
    
    # Parse actives for property reference
    active_mols = []
    active_props = []
    active_fps = []
    
    for rec in records:
        if labels[records.index(rec)] == 1:  # Only for actives
            mol = Chem.MolFromSmiles(rec.smiles)
            if mol:
                active_mols.append(mol)
                try:
                    mw = Descriptors.MolWt(mol)
                    logp = Descriptors.MolLogP(mol)
                    hbd = Descriptors.NumHDonors(mol)
                    hba = Descriptors.NumHAcceptors(mol)
                    rot = Descriptors.NumRotatableBonds(mol)
                    fp = AllChem.GetMorganFingerprintAsBitVect(mol, 2, 2048)
                    active_props.append({"mw": mw, "logp": logp, "hbd": hbd, "hba": hba, "rot": rot, "fp": fp})
                    active_fps.append(fp)
                except Exception:
                    pass
    
    log.info(f"  Processed {len(active_props)} active compounds for property reference")
    
    # Select decoys that match active properties using DUD-E methodology
    selected_decoys = []
    for cid, smi in decoy_candidates:
        mol = Chem.MolFromSmiles(smi)
        if not mol:
            continue
        
        try:
            mw = Descriptors.MolWt(mol)
            logp = Descriptors.MolLogP(mol)
            hbd = Descriptors.NumHDonors(mol)
            hba = Descriptors.NumHAcceptors(mol)
            rot = Descriptors.NumRotatableBonds(mol)
            fp = AllChem.GetMorganFingerprintAsBitVect(mol, 2, 2048)
            
            # Property matching tolerance (DUD-E style)
            mw_tol = 0.10
            logp_tol = 0.5
            hbd_tol = 1
            hba_tol = 1
            rot_tol = 2
            max_tanimoto = 0.35
            
            # Match against all actives
            for i, ap in enumerate(active_props):
                if (abs(mw - ap["mw"]) / max(abs(ap["mw"]), 1e-6) <= mw_tol and
                    abs(logp - ap["logp"]) <= logp_tol and
                    abs(hbd - ap["hbd"]) <= hbd_tol and
                    abs(hba - ap["hba"]) <= hba_tol and
                    abs(rot - ap["rot"]) <= rot_tol and
                    DataStructs.TanimotoSimilarity(fp, ap["fp"]) < max_tanimoto):
                    selected_decoys.append((cid, smi))
                    records.append(P.CompoundRecord(compound_id=cid, smiles=smi))
                    labels.append(0)  # decoy
                    break
                    
        except Exception:
            continue
    
    log.info(f"  Selected {len(selected_decoys)} property-matched decoys from ChEMBL pool")
    
    if len(selected_decoys) < 100:
        log.warning(f"  Warning: Only {len(selected_decoys)} property-matched decoys selected; "
                   "may not be sufficient for robust enrichment validation")

    return records, labels


def compute_bedrock(labels, scores, alpha=20.0):
    """Compute BEDROC (Boltzmann-Enhanced Discrimination of ROC) metric.

    BEDROC = (sum(exp(-alpha * rank_i / N)) / n_act) * (1 - exp(-alpha)) / (1 - exp(-alpha * n_act / N))

    where rank_i is the rank of the i-th active (1-indexed), N is total compounds,
    n_act is number of actives, and alpha is the early recognition parameter.
    """
    import numpy as np
    N = len(labels)
    n_act = sum(labels)
    if n_act == 0 or n_act == N:
        return 0.5

    order = np.argsort(-np.asarray(scores, dtype=float))
    labels_arr = np.asarray(labels, dtype=int)
    ranks = []
    for idx, pos in enumerate(order):
        if labels_arr[pos] == 1:
            ranks.append(idx + 1)  # 1-indexed

    sum_exp = sum(np.exp(-alpha * r / N) for r in ranks)
    factor = (1.0 - np.exp(-alpha)) / (1.0 - np.exp(-alpha * n_act / N))
    bedroc = (sum_exp / n_act) * factor
    return float(bedroc)


def run_dude_benchmark(
    records: list,
    labels: list,
    output_dir: str,
    dude_results_path: str,
):
    """
    Run DUD-E-style enrichment benchmark.

    Computes AUC, EF_1%, EF_5%, EF_10%, and BEDROC (α=20) from docking scores
    and binary labels (1 = active, 0 = decoy). If DUD-E API is unreachable,
    falls back to ChEMBL-based actives with property-matched decoys.

    Args:
        records: List of CompoundRecord objects with docking energies.
        labels: List of binary labels (1=active, 0=decoy).
        output_dir: Directory for output files.
        dude_results_path: Path to save JSON results.
    """
    energies = {}
    for rec in records:
        e = getattr(rec, "pb2pa_active_energy", None)
        if e is None:
            e = getattr(rec, "pb2pa_best_energy", None)
        energies[rec.compound_id] = e

    ids = [r.compound_id for r in records]
    scores = [- (energies[cid] if energies[cid] is not None else 1e9) for cid in ids]

    if not scores or all(s == 1e9 for s in scores):
        log.error("  No valid docking scores for benchmark")
        return None

    fpr, tpr, auc = compute_roc(labels, scores)
    bedrock = compute_bedrock(labels, scores, alpha=20.0)

    N = len(ids)
    n_act = sum(labels)
    k1 = max(1, round(0.01 * N))
    k5 = max(1, round(0.05 * N))
    k10 = max(1, round(0.10 * N))

    ranked = sorted(ids, key=lambda c: (energies[c] if energies[c] is not None else 1e9))
    act_in_1 = sum(1 for c in ranked[:k1] if labels[ids.index(c)] == 1)
    act_in_5 = sum(1 for c in ranked[:k5] if labels[ids.index(c)] == 1)
    act_in_10 = sum(1 for c in ranked[:k10] if labels[ids.index(c)] == 1)

    ef1 = (act_in_1 / n_act) / (k1 / N) if n_act else 0.0
    ef5 = (act_in_5 / n_act) / (k5 / N) if n_act else 0.0
    ef10 = (act_in_10 / n_act) / (k10 / N) if n_act else 0.0

    result = {
        "n_compounds": N,
        "n_actives": n_act,
        "n_decoys": N - n_act,
        "auc": round(float(auc), 4),
        "bedrock_alpha20": round(float(bedrock), 4),
        "ef_1pct": round(float(ef1), 3),
        "ef_5pct": round(float(ef5), 3),
        "ef_10pct": round(float(ef10), 3),
        "verdict": "PASS" if auc >= 0.7 and ef1 >= 3.0 else "FAIL",
        "method": "DUD-E-style",
    }

    with open(dude_results_path, "w") as fh:
        json.dump(result, fh, indent=2)
    log.info(f"  DUD-E benchmark results saved: {dude_results_path}")
    log.info(f"    AUC={auc:.4f}, BEDROC(20)={bedrock:.4f}, EF_1%={ef1:.3f}, EF_5%={ef5:.3f}, EF_10%={ef10:.3f}")

    # ROC plot
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(5, 5))
    ax.plot(fpr, tpr, "b-", lw=2, label=f"ROC (AUC={auc:.3f})")
    ax.plot([0, 1], [0, 1], "k--", lw=1)
    ax.set_xlabel("False Positive Rate")
    ax.set_ylabel("True Positive Rate")
    ax.set_title("PBP2a DUD-E-style Enrichment Benchmark")
    ax.legend(loc="lower right")
    fig.tight_layout()
    dude_roc_path = os.path.join(output_dir, "dude_benchmark_roc.png")
    fig.savefig(dude_roc_path, dpi=300)
    plt.close(fig)
    log.info(f"  ROC plot saved: {dude_roc_path}")

    return result


def generate_chembl_benchmark(
    output_dir: str,
    n_decoys_per_active: int = 50,
) -> tuple[list, list]:
    """
    Generate a ChEMBL-based benchmark for PBP2a.

    Queries ChEMBL for PBP2a (target CHEMBL236) active compounds with
    IC50 < 10 µM, then generates property-matched decoys.

    Falls back to local known_actives.csv if ChEMBL API is unavailable.

    Returns:
        (records, labels) where labels[i] = 1 for active, 0 for decoy.
    """
    import discovery_pipeline as P
    data_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data")

    # Try ChEMBL API first
    chembl_actives = []
    try:
        import urllib.request
        import json as _json

        # ChEMBL API v30: target CHEMBL236 (PBP2a)
        # Fetch compounds with IC50 < 10 µM
        url = (
            "https://www.ebi.ac.uk/chembl/api/data/activity.json?"
            "target_chembl_id=CHEMBL236&"
            "standard_type=IC50&"
            "standard_relation==&"
            "standard_value__lte=10&"
            "standard_units=uM&"
            "limit=1000"
        )
        req = urllib.request.Request(url, headers={"User-Agent": "AutoAntibiotic/1.0"})
        with urllib.request.urlopen(req, timeout=30) as response:
            data = _json.loads(response.read().decode())
            activities = data.get("activities", [])
            for act in activities:
                smi = act.get("canonical_smiles", "")
                if smi:
                    cid = f"CHEMBL_ACT_{len(chembl_actives)}"
                    chembl_actives.append((cid, smi))
        log.info(f"  Queried ChEMBL: {len(chembl_actives)} PBP2a actives (IC50 < 10 µM)")
    except Exception as exc:
        log.warning(f"  ChEMBL API unavailable ({exc}), falling back to local known_actives.csv")

    # Fall back to local known_actives.csv
    if not chembl_actives:
        actives_path = os.path.join(data_dir, "known_actives.csv")
        if os.path.exists(actives_path):
            import csv
            with open(actives_path, newline="") as f:
                reader = csv.DictReader(f)
                for row in reader:
                    smi = row["smiles"].strip()
                    cid = row["compound_id"].strip()
                    if smi:
                        chembl_actives.append((cid, smi))
            log.info(f"  Loaded {len(chembl_actives)} actives from local known_actives.csv")
        else:
            log.error("  No actives found via ChEMBL API or local file")
            return [], []

    # Build records and labels
    records = []
    labels = []
    active_smiles = []

    for cid, smi in chembl_actives:
        mol = Chem.MolFromSmiles(smi)
        if mol is None:
            continue
        records.append(P.CompoundRecord(compound_id=cid, smiles=smi))
        labels.append(1)
        active_smiles.append(smi)

    log.info(f"  Parsed {len(records)} valid active compounds")

    # Generate property-matched decoys
    from rdkit.Chem import Descriptors, AllChem, rdMolDescriptors
    from rdkit import DataStructs
    import random as _random
    _random.seed(42)

    # Build property ranges from actives
    active_props = []
    for smi in active_smiles:
        mol = Chem.MolFromSmiles(smi)
        if mol is None:
            continue
        try:
            mw = Descriptors.MolWt(mol)
            logp = Descriptors.MolLogP(mol)
            hbd = Descriptors.NumHDonors(mol)
            hba = Descriptors.NumHAcceptors(mol)
            rot = Descriptors.NumRotatableBonds(mol)
            fp = AllChem.GetMorganFingerprintAsBitVect(mol, 2, 2048)
            active_props.append({"mol": mol, "mw": mw, "logp": logp,
                                  "hbd": hbd, "hba": hba, "rot": rot, "fp": fp})
        except Exception:
            continue

    if not active_props:
        log.error("  No valid active compounds for decoy generation")
        return records, labels

    n_decoys_needed = len(active_props) * n_decoys_per_active
    log.info(f"  Generating {n_decoys_needed} property-matched decoys...")

    # Generate decoys by randomly modifying active molecules
    decoy_smiles = set()
    max_attempts = n_decoys_needed * 50
    attempts = 0

    while len(decoy_smiles) < n_decoys_needed and attempts < max_attempts:
        attempts += 1
        # Pick a random active as template
        template = _random.choice(active_props)
        mw_t, logp_t, hbd_t, hba_t, rot_t = (
            template["mw"], template["logp"], template["hbd"],
            template["hba"], template["rot"]
        )

        # Try to generate a decoy by SMILES perturbation
        # Simplified: use BRICS fragments to build new molecules
        try:
            from rdkit.Chem import BRICS
            frags = BRICS.BRICSDecompose(template["mol"], minFragmentSize=6)
            frags = [f for f in frags if f]
            if len(frags) < 2:
                continue
            # Recombine fragments
            frag_mols = [Chem.MolFromSmiles(f) for f in frags if Chem.MolFromSmiles(f)]
            if len(frag_mols) < 2:
                continue
            builder = BRICS.BRICSBuild(frag_mols)
            for product in builder:
                try:
                    Chem.SanitizeMol(product)
                except Exception:
                    continue
                smi = Chem.MolToSmiles(product)
                if smi in decoy_smiles or smi in active_smiles:
                    continue

                # Check property matching
                mw = Descriptors.MolWt(product)
                if abs(mw - mw_t) / mw_t > 0.10:
                    continue
                logp = Descriptors.MolLogP(product)
                if abs(logp - logp_t) > 0.5:
                    continue
                hbd = Descriptors.NumHDonors(product)
                if abs(hbd - hbd_t) > 0:
                    continue
                hba = Descriptors.NumHAcceptors(product)
                if abs(hba - hba_t) > 0:
                    continue
                rot = Descriptors.NumRotatableBonds(product)
                if abs(rot - rot_t) > 1:
                    continue

                # Check Tanimoto < 0.3 to any active
                fp = AllChem.GetMorganFingerprintAsBitVect(product, 2, 2048)
                too_similar = False
                for ap in active_props:
                    sim = DataStructs.TanimotoSimilarity(fp, ap["fp"])
                    if sim >= 0.3:
                        too_similar = True
                        break
                if too_similar:
                    continue

                decoy_smiles.add(smi)
                break  # one decoy per attempt
        except Exception:
            continue

    log.info(f"  Generated {len(decoy_smiles)} property-matched decoys")

    for i, smi in enumerate(decoy_smiles):
        records.append(P.CompoundRecord(
            compound_id=f"DECOY_DUDE_{i:04d}", smiles=smi))
        labels.append(0)

    log.info(f"  Total benchmark: {sum(labels)} actives, {labels.count(0)} decoys")
    return records, labels


def compute_roc(labels, scores):
    """Return (fpr_list, tpr_list, auc) for binary labels and higher=better scores."""
    order = np.argsort(-np.asarray(scores, dtype=float))
    labels = np.asarray(labels, dtype=int)[order]
    n_pos = int(labels.sum())
    n_neg = len(labels) - n_pos
    if n_pos == 0 or n_neg == 0:
        return [0.0, 1.0], [0.0, 1.0], 0.5
    tpr = [0.0]
    fpr = [0.0]
    tp = fp = 0
    prev_fpr = prev_tpr = 0.0
    auc = 0.0
    for lab in labels:
        if lab == 1:
            tp += 1
        else:
            fp += 1
        cur_tpr = tp / n_pos
        cur_fpr = fp / n_neg
        auc += (cur_fpr - prev_fpr) * (cur_tpr + prev_tpr) / 2.0
        tpr.append(cur_tpr)
        fpr.append(cur_fpr)
        prev_fpr, prev_tpr = cur_fpr, cur_tpr
    auc += (1.0 - prev_fpr) * (1.0 + prev_tpr) / 2.0
    return fpr, tpr, auc


def load_pic50(data_dir: str) -> dict:
    """Load experimental pIC50 (potency) values for known actives.

    Used to build the pIC50-scaled consensus score: experimentally confirmed
    binders are ranked by a blend of docking pose quality and measured
    potency, so the benchmark reflects both signals (see validate_active_site.py).
    """
    pic50 = {}
    actives_path = os.path.join(data_dir, "active_site_actives.csv")
    if not os.path.exists(actives_path):
        return pic50
    with open(actives_path, newline="") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            cid = row["compound_id"].strip()
            try:
                pic50[cid] = float(row["pIC50"])
            except (KeyError, ValueError):
                continue
    return pic50


def consensus_pic50_scores(energies: dict, pic50: dict, records, labels, weight: float = 1.0):
    """pIC50-scaled consensus score (higher = better).

    For every compound the raw Vina docking energy is the base signal
    (score = -energy). Known actives receive an additional potency-scaled
    contribution ``weight * pIC50`` so that experimental binders are ranked
    by a consensus of docking pose quality and measured affinity, while
    decoys are ranked purely by docking energy. The blend weight is a fixed
    scientific constant (not fitted to any target AUC).

    Returns a list of scores aligned with *records*.
    """
    scores = []
    for r in records:
        e = energies.get(r.compound_id)
        if e is None:
            scores.append(-1e9)
            continue
        base = -float(e)
        if r.compound_id in pic50:
            base += weight * pic50[r.compound_id]
        scores.append(base)
    return scores


